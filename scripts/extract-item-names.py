#!/usr/bin/env python3
"""
Scrapbook item names (en/ko) → src/data/item-names.ts  (#148, 아이템 도감)
Scrapbook creature names (en/ko) → src/data/creature-names.ts  (#149, 생물 도감)

- 대상: src/data/scrapbook-stats.ts 의 `type: "item"` 항목 전부 (convert-scrapbook.py 가 먼저 돌아야 한다)
- 이름: ko.po 의 `msgctxt "STRINGS.NAMES.<ID>"` — msgid 가 영문, msgstr 가 한글이라 ko.po 하나로 둘 다 얻는다
- 이름이 없는 id 가 생기면 exit 1. 조용히 빠지면 도감에서 아이템이 사라진다 (#122·#135 와 같은 계열).
  게임에 이름 문자열이 정말 없는 항목은 NAME_ALIASES 에 "어느 STRINGS.NAMES 를 쓰는지" 명시한다

Usage: python3 scripts/extract-item-names.py  (평소엔 bash scripts/sync-game-data.sh 가 호출)
"""

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = Path(os.environ.get("DST_SNAPSHOT", Path.home() / "dst-game-snapshot"))
KO_PO = SNAPSHOT / "ko.po"
STATS = ROOT / "src/data/scrapbook-stats.ts"
OUT = ROOT / "src/data/item-names.ts"

# 스크랩북 id ≠ STRINGS.NAMES 키인 항목 (prefab 이 다른 이름 문자열을 빌려 쓴다).
# 겨울 장식품은 아래 ornament_aliases() 가 prefab 소스에서 자동으로 채운다
NAME_ALIASES: dict[str, str] = {}

OUT_CREATURES = ROOT / "src/data/creature-names.ts"

# 생물: 스크랩북 id → (STRINGS.NAMES 키, 구분용으로 괄호에 붙일 STRINGS.NAMES 키 또는 None).
# 전부 prefab 의 SetPrefabNameOverride 를 직접 확인한 것 (deer.lua:460, shadowthrall_centipede.lua:228, wobster.lua:428).
# 보석 사슴 둘은 게임 이름이 똑같이 "No-Eyed Deer" 라 박힌 보석 이름을 괄호로 덧붙여 구분한다
CREATURE_ALIASES: dict[str, tuple[str, str | None]] = {
    "deer_blue": ("deer_gemmed", "bluegem"),
    "deer_red": ("deer_gemmed", "redgem"),
    "shadowthrall_centipede_head": ("shadowthrall_centipede", None),
    "wobster_moonglass_land": ("wobster_moonglass", None),
}


def ornament_aliases() -> dict[str, str]:
    """winter_ornaments.lua: MakeOrnament("<suffix>", "<overridename>") → SetPrefabNameOverride(overridename).
    plain/fancy/light 는 for 루프에서 "plain"..i 꼴로 만든다 — NUM_*_ORNAMENT 상수로 펼친다."""
    src = (SNAPSHOT / "scripts/prefabs/winter_ornaments.lua").read_text(encoding="utf-8")
    out: dict[str, str] = {}
    for suffix, override in re.findall(r'MakeOrnament\("([a-z0-9_]+)",\s*"([a-z_]+)"', src):
        out[f"winter_ornament_{suffix}"] = override
    for kind, override in re.findall(r'MakeOrnament\("([a-z]+)"\.\.i,\s*"([a-z_]+)"', src):
        m = re.search(rf"for i = 1, (NUM_[A-Z_]+) do\s*\n\s*table\.insert\(ornament, MakeOrnament\(\"{kind}\"", src)
        assert m, f"ornament loop for {kind} not found"
        n = re.search(rf"^local {m.group(1)} = (\d+)", src, re.M)
        assert n, f"{m.group(1)} not found"
        for i in range(1, int(n.group(1)) + 1):
            out[f"winter_ornament_{kind}{i}"] = override
    assert len(out) > 40, f"ornament 파싱 결과가 너무 적다 ({len(out)})"
    return out


def parse_po(text: str) -> dict[str, tuple[str, str]]:
    names: dict[str, tuple[str, str]] = {}
    # msgid/msgstr 는 여러 줄 문자열일 수 있다 (연극 전단: "제목\\n부제"). 첫 줄(제목)만 이름으로 쓴다
    strs = r'((?:"(?:[^"\\]|\\.)*"\n?)+)'
    pat = re.compile(r'^msgctxt "STRINGS\.NAMES\.([A-Z0-9_]+)"\nmsgid ' + strs + r'msgstr ' + strs, re.M)

    def join(block: str) -> str:
        s = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', block)).replace('\\"', '"')
        return s.split("\\n")[0].strip()

    for key, en, ko in pat.findall(text):
        names[key] = (join(en), join(ko))
    return names


def main() -> None:
    names = parse_po(KO_PO.read_text(encoding="utf-8"))
    assert len(names) > 1000, f"ko.po STRINGS.NAMES 파싱 실패 ({len(names)})"

    ids = re.findall(r'^  ([a-z0-9_]+): \{type: "item"', STATS.read_text(encoding="utf-8"), re.M)
    assert len(ids) > 500, f"scrapbook-stats.ts item 파싱 실패 ({len(ids)})"

    aliases = {**ornament_aliases(), **NAME_ALIASES}
    rows: list[tuple[str, str, str]] = []
    missing: list[str] = []
    for id_ in ids:
        key = aliases.get(id_, id_).upper()
        if key not in names or not names[key][0]:
            missing.append(id_)
            continue
        en, ko = names[key]
        rows.append((id_, en, ko or en))

    if missing:
        print(f"ERROR: STRINGS.NAMES 없는 스크랩북 아이템 {len(missing)}개 — NAME_ALIASES 에 매핑할 것:", file=sys.stderr)
        print("  " + " ".join(missing), file=sys.stderr)
        sys.exit(1)

    def q(s: str) -> str:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = [
        "// Auto-generated by scripts/extract-item-names.py — DO NOT EDIT MANUALLY",
        "// Source: ko.po STRINGS.NAMES.* (msgid = en, msgstr = ko) for scrapbook type \"item\"",
        "",
        "/** 스크랩북 아이템 id → [영문 이름, 한글 이름] */",
        "export const itemNames: Record<string, readonly [en: string, ko: string]> = {",
    ]
    lines += [f"  {id_}: [{q(en)}, {q(ko)}]," for id_, en, ko in rows]
    lines += ["};", ""]

    # 스크랩북 분류(subcat) 이름 — 인게임 STRINGS.SCRAPBOOK.SUBCATS.*
    subcats = sorted(set(re.findall(r'type: "item", subcat: "([a-z_]+)"', STATS.read_text(encoding="utf-8"))))
    po = KO_PO.read_text(encoding="utf-8")
    lines += ["/** 스크랩북 아이템 분류 id → [영문, 한글] (STRINGS.SCRAPBOOK.SUBCATS) */",
              "export const itemSubcatNames: Record<string, readonly [en: string, ko: string]> = {"]
    for sc in subcats:
        m = re.search(rf'^msgctxt "STRINGS\.SCRAPBOOK\.SUBCATS\.{sc.upper()}"\nmsgid "([^"]*)"\nmsgstr "([^"]*)"', po, re.M)
        assert m, f"SCRAPBOOK.SUBCATS.{sc.upper()} 없음"
        lines.append(f"  {sc}: [{q(m.group(1))}, {q(m.group(2) or m.group(1))}],")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"item-names.ts: {len(rows)} items")
    write_creatures(names, po, q)


def po_pair(po: str, ctx: str) -> tuple[str, str]:
    m = re.search(rf'^msgctxt "{re.escape(ctx)}"\nmsgid "([^"]*)"\nmsgstr "([^"]*)"', po, re.M)
    assert m and m.group(1), f"{ctx} 없음"
    return m.group(1), m.group(2) or m.group(1)


def write_creatures(names: dict[str, tuple[str, str]], po: str, q) -> None:
    """생물 도감(#149): 스크랩북 `type: "creature"` 의 이름·분류명·관련 항목 이름·정신력 오라 문구."""
    stats = STATS.read_text(encoding="utf-8")
    entries = re.findall(r'^  ([a-z0-9_]+): \{type: "creature"(.*)$', stats, re.M)
    assert len(entries) > 150, f"scrapbook-stats.ts creature 파싱 실패 ({len(entries)})"

    rows: list[tuple[str, str, str]] = []
    missing: list[str] = []
    for id_, _ in entries:
        key, qualifier = CREATURE_ALIASES.get(id_, (id_, None))
        if key.upper() not in names or not names[key.upper()][0]:
            missing.append(id_)
            continue
        en, ko = names[key.upper()]
        ko = ko or en
        if qualifier:
            qen, qko = names[qualifier.upper()]
            en, ko = f"{en} ({qen})", f"{ko} ({qko or qen})"
        rows.append((id_, en, ko))
    if missing:
        print(f"ERROR: STRINGS.NAMES 없는 스크랩북 생물 {len(missing)}개 — prefab 의 SetPrefabNameOverride 를 확인해 CREATURE_ALIASES 에 매핑할 것:", file=sys.stderr)
        print("  " + " ".join(missing), file=sys.stderr)
        sys.exit(1)
    creature_ids = {r[0] for r in rows}

    # 관련 항목(scrapbook deps) — 인게임 스크랩북이 항목 아래에 보여 주는 연관 항목. 이름 문자열이 없는 dep
    # (석상 잔해 등 표시용 prefab)은 화면에서 빼고 여기서 개수를 알린다
    deps: set[str] = set()
    for _, rest in entries:
        m = re.search(r"deps: \[([^\]]*)\]", rest)
        if m:
            deps |= set(re.findall(r'"([a-z0-9_]+)"', m.group(1)))
    orn = ornament_aliases()
    related: list[tuple[str, str, str]] = []
    unnamed: list[str] = []
    for d in sorted(deps - creature_ids):
        key = orn.get(d, d).upper()
        if key in names and names[key][0]:
            related.append((d, names[key][0], names[key][1] or names[key][0]))
        else:
            unnamed.append(d)
    assert len(unnamed) < 15, f"이름 없는 관련 항목이 너무 많다 ({len(unnamed)}): {unnamed}"

    # 정신력 오라 문구 경계 — scrapbookscreen.lua 는 TUNING.SANITYAURA_MED / _HUGE 로 6단계를 가른다
    tuning = (SNAPSHOT / "scripts/tuning.lua").read_text(encoding="utf-8")
    seg = re.search(r"^\s*local seg_time = (\d+)", tuning, re.M)
    med = re.search(r"SANITYAURA_MED = 100/\(seg_time\*([\d.]+)\)", tuning)
    huge = re.search(r"SANITYAURA_HUGE = 100/\(seg_time\*([\d.]+)\)", tuning)
    assert seg and med and huge, "tuning.lua SANITYAURA_MED/HUGE 식이 바뀌었다"
    med_v = 100 / (int(seg.group(1)) * float(med.group(1)))
    huge_v = 100 / (int(seg.group(1)) * float(huge.group(1)))
    screen = (SNAPSHOT / "scripts/screens/redux/scrapbookscreen.lua").read_text(encoding="utf-8")
    for needle in ("data.sanityaura >= TUNING.SANITYAURA_HUGE", "data.sanityaura >= TUNING.SANITYAURA_MED",
                   "data.sanityaura > -TUNING.SANITYAURA_MED", "data.sanityaura > -TUNING.SANITYAURA_HUGE"):
        assert needle in screen, f"scrapbookscreen.lua 정신력 오라 분기가 바뀌었다: {needle}"

    lines = [
        "// Auto-generated by scripts/extract-item-names.py — DO NOT EDIT MANUALLY",
        "// Source: ko.po STRINGS.NAMES.* / STRINGS.SCRAPBOOK.* (msgid = en, msgstr = ko), tuning.lua",
        "",
        "/** 스크랩북 생물 id → [영문 이름, 한글 이름] */",
        "export const creatureNames: Record<string, readonly [en: string, ko: string]> = {",
    ]
    lines += [f"  {i}: [{q(en)}, {q(ko)}]," for i, en, ko in rows]
    lines += ["};", "",
              "/** 생물의 관련 항목(scrapbook deps) 중 생물이 아닌 것의 이름. 여기 없는 dep 은 게임에 이름이 없다 */",
              "export const creatureRelatedNames: Record<string, readonly [en: string, ko: string]> = {"]
    lines += [f"  {i}: [{q(en)}, {q(ko)}]," for i, en, ko in related]
    lines += ["};", "",
              "/** 스크랩북 생물 분류 id → [영문, 한글] (STRINGS.SCRAPBOOK.SUBCATS) */",
              "export const creatureSubcatNames: Record<string, readonly [en: string, ko: string]> = {"]
    for sc in sorted(set(re.findall(r'type: "creature", subcat: "([a-z_]+)"', stats))):
        en, ko = po_pair(po, f"STRINGS.SCRAPBOOK.SUBCATS.{sc.upper()}")
        lines.append(f"  {sc}: [{q(en)}, {q(ko)}],")
    cat_en, cat_ko = po_pair(po, "STRINGS.SCRAPBOOK.CATS.CREATURES")
    lines += ["};", "",
              "/** 스크랩북 대분류 이름 (STRINGS.SCRAPBOOK.CATS.CREATURES) */",
              f"export const creatureCategoryName = [{q(cat_en)}, {q(cat_ko)}] as const;", "",
              "/** 정신력 오라 문구 경계 (TUNING.SANITYAURA_MED / _HUGE, 초당) — scrapbookscreen.lua 분기 그대로 */",
              f"export const SANITYAURA_MED = {med_v!r};",
              f"export const SANITYAURA_HUGE = {huge_v!r};", "",
              "/** 정신력 오라 문구 (STRINGS.SCRAPBOOK.SANITYDESC) */",
              "export const sanityAuraDesc = {"]
    for k in ("POSHIGH", "POSMED", "POSSMALL", "NEGSMALL", "NEGMED", "NEGHIGH"):
        en, ko = po_pair(po, f"STRINGS.SCRAPBOOK.SANITYDESC.{k}")
        lines.append(f"  {k}: [{q(en)}, {q(ko)}],")
    lines += ["} as const;", ""]
    OUT_CREATURES.write_text("\n".join(lines), encoding="utf-8")
    print(f"creature-names.ts: {len(rows)} creatures, {len(related)} related names"
          + (f" (이름 없는 관련 항목 {len(unnamed)}개 제외: {' '.join(unnamed)})" if unnamed else ""))


if __name__ == "__main__":
    main()
